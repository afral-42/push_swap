#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*tmp;

	if (!lst || !(*lst) || !del)
		return ;
	tmp = (*lst)->next;
	ft_lstdelone(*lst, del);
	*lst = tmp;
	ft_lstclear(lst, del);
}
